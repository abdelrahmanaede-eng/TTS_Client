def t(key: str, lang: str = "en", **kwargs: Any) -> str:
    """Translate a key into the target language ('en' or 'ar').

    Falls back to English if the translation is not found.
    """
    selected_lang = lang if lang in TRANSLATIONS else "en"
    text = TRANSLATIONS[selected_lang].get(key)
    if text is None:
        text = TRANSLATIONS["en"].get(key, key)

    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
